def get_string(key: str, locale: str = "en") -> str:
    """Get localized string by key."""
    if locale == "hi":
        return STRINGS_HI.get(key, STRINGS_EN.get(key, key))
    return STRINGS_EN.get(key, key)


def get_currency_string(currency: str, locale: str = "en") -> str:
    """Get currency as localized string."""
    if locale == "hi":
        return CURRENCY_STRINGS["hi"].get(currency, currency)
    return CURRENCY_STRINGS["en"].get(currency, currency)


